export function readingTime(article: Article) {
  const extra = article.slug === 'optimus-evolution' ? generations.map(g => Object.values(g).join(' ')).join(' ') : '';
  const text = article.sections.map(s => s.title + ' ' + s.paragraphs.join(' ')).join(' ') + extra;
  return Math.max(1, Math.ceil(text.trim().split(/\s+/u).length / 180));
}
